interface Turn {
  prompt: string;
  firstByteMs: number;
  buildsMs: number | null;
  doneMs: number;
  builds: number;
  mode: string;
}

async function turn(prompt: string): Promise<Turn> {
  const cookie = `gid=perf${randomBytes(9).toString('base64url')}`;
  const session = await fetch(`${API_URL}/chat/sessions`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', cookie },
    body: '{}',
  });
  if (session.status !== 201) throw new Error(`session ${session.status}`);
  const { id } = (await session.json()) as { id: string };

  const t0 = performance.now();
  const res = await fetch(`${API_URL}/chat/sessions/${id}/messages`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', cookie },
    body: JSON.stringify({ text: prompt }),
  });
  if (res.status !== 200 || !res.body) throw new Error(`message ${res.status}`);
  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let firstByteMs = -1;
  let buildsMs: number | null = null;
  let builds = 0;
  let mode = '?';
  let buffer = '';
  for (;;) {
    const { value, done } = await reader.read();
    if (done) break;
    if (firstByteMs < 0) firstByteMs = performance.now() - t0;
    buffer += decoder.decode(value, { stream: true });
    let cut = buffer.indexOf('\n\n');
    while (cut >= 0) {
      const chunk = buffer.slice(0, cut).trim();
      buffer = buffer.slice(cut + 2);
      cut = buffer.indexOf('\n\n');
      if (!chunk.startsWith('data:')) continue;
      const ev = JSON.parse(chunk.slice(5).trim()) as ChatEvent;
      if (ev.type === 'builds' && buildsMs === null) {
        buildsMs = performance.now() - t0;
        builds = ev.builds.length;
      }
      if (ev.type === 'done') mode = ev.mode;
    }
  }
  return { prompt, firstByteMs, buildsMs, doneMs: performance.now() - t0, builds, mode };
}

const stats = (xs: number[]) => ({
  p50: round1(percentile(xs, 50)),
  p95: round1(percentile(xs, 95)),
  max: round1(Math.max(...xs)),
  mean: round1(xs.reduce((s, x) => s + x, 0) / xs.length),
});

await assertApiUp();
const env = environment();
await bumpCatalogVersion();
const turns: Turn[] = [];
for (const prompt of PROMPTS) turns.push(await turn(prompt));

const withBuilds = turns.filter((t) => t.buildsMs !== null);
const summary = {
  turns: turns.length,
  turnsWithBuilds: withBuilds.length,
  modes: [...new Set(turns.map((t) => t.mode))],
  firstByteMs: stats(turns.map((t) => t.firstByteMs)),
  timeToBuildsMs: stats(withBuilds.map((t) => t.buildsMs as number)),
  doneMs: stats(turns.map((t) => t.doneMs)),
};

