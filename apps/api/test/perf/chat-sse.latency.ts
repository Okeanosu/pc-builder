/**
 * Chat turn latency over SSE in fallback mode: 20 sequential first turns, each in a new session with its own
 * guest cookie (so neither the session nor the message rate limit applies). Measured from the moment the
 * POST is sent: first byte, first `builds` event, `done` event. The recommendation cache is made cold first.
 * Usage (API running, see perf-env.ts): `pnpm exec tsx test/perf/chat-sse.latency.ts` from apps/api.
 */
