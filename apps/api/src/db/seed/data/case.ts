export const CASES: SeedProduct<'case'>[] = ROWS.map(
  ([brand, code, name, board, gpuMax, coolerMax, rads, psuForms, color, price, stock]) => {
    const specs: CaseSpecs = {
      supportedFormFactors: BOARDS[board],
      maxGpuLengthMm: gpuMax,
      maxCoolerHeightMm: coolerMax,
      radiatorSupportMm: rads,
      psuFormFactors: psuForms,
      color,
    };
    return {
      sku: sku('case', brand, code),
      brand,
      name,
      price,
      stock,
      specs,
      description: `Vỏ case ${name}: hỗ trợ mainboard ${BOARDS[board].join('/')}, card đồ họa dài tối đa ${gpuMax}mm, tản khí cao tối đa ${coolerMax}mm.`,
    };
  },
);
